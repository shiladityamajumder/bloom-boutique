import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { suppliedAssets, generatedAssets, imageAliases } from "./asset-map.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const assets = [
  ...suppliedAssets.filter((asset) => !asset.referenceOnly),
  ...generatedAssets,
];
const images = {};
const records = [];

for (const asset of assets) {
  const relativeOutput = asset.source.replace(/\.png$/, ".webp");
  const output = path.join(root, "public/images", relativeOutput);
  await mkdir(path.dirname(output), { recursive: true });
  // Resize the complete image proportionally. Never extract a board region.
  const info = await sharp(path.join(root, "assets", asset.source))
    .resize({
      width:
        asset.key.includes("hero") || asset.key.includes("background")
          ? 1672
          : 1100,
      withoutEnlargement: true,
    })
    .webp({ quality: 86 })
    .toFile(output);
  images[asset.key] = `/images/${relativeOutput}`;
  records.push({
    source: asset.source,
    url: images[asset.key],
    width: info.width,
    height: info.height,
    generated: generatedAssets.includes(asset),
  });
}

for (const [alias, original] of Object.entries(imageAliases)) {
  if (!images[original])
    throw new Error(`Missing image alias target: ${original}`);
  images[alias] = images[original];
}

await writeFile(
  path.join(root, "src/lib/images.ts"),
  `// Generated by npm run assets:prepare from the project's local asset library.\nexport const imagePaths = ${JSON.stringify(images, null, 2)} as const;\n\nexport type ImageName = keyof typeof imagePaths;\n\nexport function imagePath(name: string): string {\n  const url = imagePaths[name as ImageName];\n  if (!url) throw new Error(\`Unknown image: \${name}\`);\n  return url;\n}\n`,
);
await writeFile(
  path.join(root, "assets/optimized-assets.json"),
  JSON.stringify(records, null, 2),
);
console.log(
  `Prepared ${assets.length} complete standalone images from local assets. Reference sheets were excluded.`,
);
